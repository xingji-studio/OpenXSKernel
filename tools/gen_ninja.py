#!/usr/bin/env python3
"""leopard-xsk 独立构建：生成只产出内核 out/kernel.krl 的 build.ninja。"""
import os
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def kernel_version_from_tag():
    """Return the kernel release string, kept in sync with the git tag."""
    fallback = "2.2.1"
    try:
        tag = subprocess.check_output(
            ["git", "-C", str(ROOT), "describe", "--tags", "--exact-match", "HEAD"],
            text=True, stderr=subprocess.DEVNULL).strip()
    except (subprocess.CalledProcessError, FileNotFoundError):
        try:
            tag = subprocess.check_output(
                ["git", "-C", str(ROOT), "describe", "--tags", "--abbrev=0"],
                text=True, stderr=subprocess.DEVNULL).strip()
        except (subprocess.CalledProcessError, FileNotFoundError):
            tag = "v" + fallback
    if tag.startswith("v"):
        tag = tag[1:]
    return tag or fallback


def write_build_config():
    """Generate the gitignored kernel/build_config.h consumed by build_settings.h."""
    version = kernel_version_from_tag()
    config = (
        "/* Generated by tools/gen_ninja.py; do not edit. */\n"
        "#pragma once\n"
        f'#define CONFIG_KN_VERSION "XSK {version}"\n'
    )
    (ROOT / "kernel" / "build_config.h").write_text(config, encoding="utf-8")


def find(base, suffixes):
    root = ROOT / base
    if not root.exists():
        return []
    return sorted(p for p in root.rglob("*") if p.is_file() and p.suffix in suffixes)


def esc(p):
    return str(p).replace("$", "$$").replace(":", "$:").replace(" ", "$ ")


def main():
    write_build_config()

    prefix = os.environ.get("COMPILER_PREFIX", "")
    cc = os.environ.get("CC", prefix + "clang")
    cxx = os.environ.get("CPP", prefix + "clang++")
    nasm = os.environ.get("NASM", prefix + "nasm")
    ld = os.environ.get("LD", prefix + "ld")
    objc = os.environ.get("OBJC", prefix + "objcopy")
    opt = "-O" + os.environ.get("OPT_LEVEL", "2")
    color = os.environ.get("DIAGNOSTICS_COLOR", "-fdiagnostics-color=always")
    builtin_xhci = os.environ.get("BUILTIN_XHCI", "0") == "1"

    dirs = ["kernel", "driver", "lib"]
    nasm_files = [p for d in dirs for p in find(d, (".asm",))]
    asm_files = [p for d in dirs for p in find(d, (".S",))]
    c_files = [p for d in dirs for p in find(d, (".c",))]
    cpp_files = [p for d in dirs for p in find(d, (".cpp",))]
    cpp_files = [p for p in cpp_files if p.name != "stress.cpp"]
    if builtin_xhci:
        cpp_files += find("kmod/xhci", (".cpp",))

    asm_flags = (f"{color} {opt} -g -mno-red-zone -mstackrealign -nostdlib -ffreestanding "
                 "-fno-builtin -m64 -fno-stack-protector -fno-exceptions -fno-strict-aliasing "
                 "-mno-80387 -MMD -MP")
    c_flags = (f"{color} {opt} -g -mno-red-zone -mstackrealign -nostdlib -ffreestanding "
               "-fno-builtin -m64 -fno-stack-protector -fno-exceptions -fno-strict-aliasing "
               "-std=c11 -fshort-wchar -nostdinc -mno-80387 -I./include -MMD -MP")
    cpp_flags = (f"{color} {opt} -g -mno-red-zone -mstackrealign -nostdlib -ffreestanding "
                 "-fno-builtin -m64 -fno-stack-protector -fno-exceptions -fno-strict-aliasing "
                 "-fno-rtti -std=gnu++17 -fshort-wchar -nostdinc -fno-use-cxa-atexit "
                 "-fno-threadsafe-statics -mno-80387 -Wno-int-to-pointer-cast -Wno-macro-redefined "
                 "-Wno-c11-extensions -Wno-c99-extensions -Wno-gnu-statement-expression-from-macro-expansion "
                 "-I./include -Wno-writable-strings -Wno-c++11-narrowing -MMD -MP")
    if builtin_xhci:
        cpp_flags += " -DXHCI_BUILTIN"

    L = ["# leopard-xsk 专用：只构建内核", "ninja_required_version = 1.10"]
    L += [f"cc = {cc}", f"cxx = {cxx}", f"nasm = {nasm}", f"ld = {ld}", f"objc = {objc}"]
    L += [f"asm_flags = {asm_flags}", f"c_flags = {c_flags}", f"cpp_flags = {cpp_flags}",
          "nasm_flags = -f elf64 -DX86_64_TARGET -DUEFI", ""]
    L += [
        "rule nasm",
        "  command = mkdir -p $$(dirname $out) && $nasm $nasm_flags $in -o $out",
        "",
        "rule root_as",
        "  command = mkdir -p $$(dirname $out) && $cc -mcmodel=large $asm_flags -MF $out.d -c $in -o $out",
        "  depfile = $out.d",
        "  deps = gcc",
        "",
        "rule root_cc",
        "  command = mkdir -p $$(dirname $out) && $cc -fno-pic -fno-pie -mcmodel=large $c_flags -MF $out.d -c $in -o $out",
        "  depfile = $out.d",
        "  deps = gcc",
        "",
        "rule root_cxx",
        "  command = mkdir -p $$(dirname $out) && $cxx -fno-pic -fno-pie -mcmodel=large $cpp_flags -MF $out.d -c $in -o $out",
        "  depfile = $out.d",
        "  deps = gcc",
        "",
        "rule objcopy_bin",
        "  command = mkdir -p $$(dirname $out) && $objc -I binary -O elf64-x86-64 $bin_input $out",
        "",
        "rule kernel_link",
        "  command = $ld -z muldefs -T linker.ld --static --wrap=malloc --wrap=calloc --wrap=free --wrap=realloc --wrap=aligned_alloc -o $out $in",
        "",
        "rule kmod_cxx",
        "  command = mkdir -p $$(dirname $out) && $cxx -fPIC -fvisibility=hidden $cpp_flags $extra_flags -MF $out.d -c $in -o $out",
        "  depfile = $out.d",
        "  deps = gcc",
        "",
        "rule kmod_cc",
        "  command = mkdir -p $$(dirname $out) && $cc -fPIC -fvisibility=hidden $c_flags $extra_flags -MF $out.d -c $in -o $out",
        "  depfile = $out.d",
        "  deps = gcc",
        "",
        "rule kmod_link",
        "  command = $cxx -shared $in -nostdlib -Wl,-e,dlmain $extra_ldflags -o $out",
        "",
    ]
    objs = []
    for rule, files in (("nasm", nasm_files), ("root_as", asm_files),
                        ("root_cc", c_files), ("root_cxx", cpp_files)):
        for src in files:
            rel_src = src.relative_to(ROOT)
            obj = Path("out") / rel_src.with_suffix(".o")
            L += [f"build {esc(obj)}: {rule} {esc(rel_src)} | kernel/build_settings.h"]
            objs.append(obj)
        L += [""]

    L += ["build out/font/hankaku.o: objcopy_bin font/hankaku.bin",
          "  bin_input = ./font/hankaku.bin", ""]
    inputs = " ".join(esc(o) for o in objs) + " out/font/hankaku.o liballoc-x86_64.a"
    L += [f"build out/kernel.krl: kernel_link {inputs} | linker.ld", ""]

    # ---- 可加载内核模块（kmod/<name>/ -> out/kmod/<name>.sys）----
    # Each module is packaged independently; the kernel package never contains it.
    all_mod_sys = []
    all_mod_pkgs = []
    kmod_root = ROOT / "kmod"
    for module_dir in sorted(p for p in kmod_root.iterdir() if p.is_dir()) if kmod_root.exists() else []:
        name = module_dir.name
        conf = {}
        conf_path = module_dir / "module.conf"
        if conf_path.is_file():
            for line in conf_path.read_text(encoding="utf-8").splitlines():
                line = line.strip()
                if not line or line.startswith("#") or "=" not in line:
                    continue
                key, value = line.split("=", 1)
                conf[key.strip()] = value.strip()
        if conf.get("sources"):
            sources = [module_dir / item.strip() for item in conf["sources"].split(",") if item.strip()]
        else:
            sources = sorted([*module_dir.rglob("*.cpp"), *module_dir.rglob("*.c")])
        if not sources:
            continue
        includes = " ".join(f"-I{ROOT / item.strip()}" for item in conf.get("includes", "").split(",") if item.strip())
        extra_c = (includes + " " + conf.get("cflags", "")).strip()
        extra_cxx = (includes + " " + conf.get("cxxflags", "")).strip()
        mod_objs = []
        for src in sources:
            rel_src = src.relative_to(ROOT)
            obj = Path("out") / "kmod" / name / rel_src.relative_to(Path("kmod") / name).with_suffix(".o")
            rule = "kmod_cc" if src.suffix == ".c" else "kmod_cxx"
            extra = extra_c if src.suffix == ".c" else extra_cxx
            L += [f"build {esc(obj)}: {rule} {esc(rel_src)}"]
            if extra:
                L += [f"  extra_flags = {extra}"]
            mod_objs.append(obj)
        target = Path("out") / "kmod" / f"{name}-kmod.sys"
        L += [f"build {esc(target)}: kmod_link " + " ".join(esc(o) for o in mod_objs)]
        if conf.get("ldflags"):
            L += [f"  extra_ldflags = {conf['ldflags']}"]
        L += [""]
        all_mod_sys.append(target)
        L += [f"build kmod-{name}: phony {esc(target)}", ""]

        # module.conf: package=0 keeps a sample/skeleton out of the package set.
        if conf.get("package", "1") != "0":
            ver = conf.get("version", "1.0_1")
            pkgname = f"{name}-kmod"
            desc = conf.get("description", f"leopard-xsk module {name}")
            pkg_out = Path("out") / f"{pkgname}-{ver}.x86_64.xbps"
            stage = f".pkg-kmod-{name}"
            args = f"-A x86_64 -n {pkgname}-{ver} -s '{desc}' -D 'leopard-xsk>=2.2.0_2'"
            cmd = (f"rm -rf {stage} && mkdir -p {stage}/mod && cp {esc(target)} {stage}/mod/{name}-kmod.sys && "
                   f"cd out && xbps-create --compression gzip {args} ../{stage}")
            L += [f"rule package_kmod_{name}", f"  command = {cmd}", ""]
            L += [f"build {esc(pkg_out)}: package_kmod_{name} {esc(target)}", ""]
            all_mod_pkgs.append(pkg_out)
            L += [f"build pack-kmod-{name}: phony {esc(pkg_out)}", ""]

    L += ["build kmods: phony " + " ".join(esc(x) for x in all_mod_sys), ""]
    L += ["build pack-kmods: phony " + " ".join(esc(x) for x in all_mod_pkgs), ""]

    # ---- xbps 打包（pack）----
    pkg = {"name": "leopard-xsk", "ver": "2.2.1_1", "arch": "x86_64",
           "desc": "Leopard kernel", "install": "system/kernel.krl"}
    pkg_args = (f"-A {pkg['arch']} -n {pkg['name']}-{pkg['ver']} -s '{pkg['desc']}' "
                f"-D 'leopard-boot>=2.1.1_2'")
    xbps_out = f"out/{pkg['name']}-{pkg['ver']}.{pkg['arch']}.xbps"
    L += [
        "rule package",
        f"  command = rm -rf .pkg && mkdir -p .pkg/$$(dirname {pkg['install']}) && "
        f"cp out/kernel.krl .pkg/{pkg['install']} && cd out && xbps-create --compression gzip {pkg_args} ../.pkg",
        "",
        f"build {xbps_out}: package out/kernel.krl",
        "build build: phony out/kernel.krl",
        f"build pack: phony {xbps_out}",
        "default build", "",
        "rule clean", "  command = rm -rf out kernel/build_config.h .pkg .pkg-kmod-*", "build clean: clean",
    ]

    (ROOT / "build.ninja").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("已生成 build.ninja（仅内核）。构建：ninja")


if __name__ == "__main__":
    main()

